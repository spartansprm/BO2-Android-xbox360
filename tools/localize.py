#!/usr/bin/env python3


import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ap = argparse.ArgumentParser()
ap.add_argument("--gen", default=os.path.join(ROOT, "app", "generated", "default_mp"))
ap.add_argument("--list", default=os.path.join(ROOT, "app", "locals.txt"))
args = ap.parse_args()

fn_names = []
with open(args.list, encoding="utf-8") as f:
    for line in f:
        line = line.split("#", 1)[0].strip()
        if line:
            if not re.fullmatch(r"sub_[0-9A-F]{8}", line):
                sys.exit(f"localize: bad name {line!r} in {args.list}")
            fn_names.append(line)


bodies = {}
for file_name in sorted(os.listdir(args.gen)):
    if not re.fullmatch(r"bo2zm_recomp\.\d+\.cpp", file_name):
        continue
    with open(os.path.join(args.gen, file_name), encoding="utf-8") as f:
        text = f.read()
    for m in re.finditer(r"^DEFINE_REX_FUNC\((sub_[0-9A-F]{8})\) \{\n(.*?)^\}\n", text, re.M | re.S):
        if m.group(1) in fn_names:
            bodies[m.group(1)] = m.group(2)

REG = re.compile(r"\bctx\.([rfv]\d+)\b")
CALL = re.compile(r"^\s*(?:__imp__)?sub_[0-9A-F]{8}\(ctx, base\);\s*$")
CALLEE = re.compile(r"^\s*((?:__imp__)?sub_[0-9A-F]{8})\(ctx, base\);\s*$")


def reg_order(r):
    return ("rfv".index(r[0]), int(r[1:]))


cpp_parts = []
callees = set()
header_lines = []
for fn_name in fn_names:
    if fn_name not in bodies:
        sys.exit(f"localize: {fn_name} not found in {args.gen}")
    body = bodies[fn_name]
    regs = sorted(set(REG.findall(body)), key=reg_order)
    write_back = " ".join(f"ctx.{r} = c_{r};" for r in regs)
    reload = " ".join(f"c_{r} = ctx.{r};" for r in regs)
    out_lines = []
    for line in body.split("\n"):
        localized = REG.sub(lambda m: "c_" + m.group(1), line)

        rest = re.sub(r"\bctx\.(fpscr|lr|msr|vscr_sat)\b", "", localized)
        if CALL.match(line):
            callees.add(CALLEE.match(line).group(1))
            out_lines.append(f"\t{{ {write_back} }}")
            out_lines.append(localized)
            out_lines.append(f"\t{{ {reload} }}")
            continue
        if re.search(r"\bctx\b", rest):
            sys.exit(f"localize: {fn_name} uses ctx in a form this tool does not handle:\n  {line.strip()}")
        localized = re.sub(r"\breturn;", f"{{ {write_back} return; }}", localized)
        out_lines.append(localized)
    decls = "\n".join(f"\tauto c_{r} = ctx.{r};" for r in regs)
    cpp_parts.append(
        f"// {fn_name} with its ctx registers as locals ({len(regs)}: {', '.join(regs)}).\n"
        f"extern \"C\" REX_FUNC(local_{fn_name}) {{\n{decls}\n" + "\n".join(out_lines).rstrip("\n") +
        f"\n\t{write_back}\n}}\n")
    header_lines.append(f"extern \"C\" void local_{fn_name}(PPCContext& __restrict ctx, uint8_t* base);\n"
                    f"#define BO2ZM_LOCALS_{fn_name} 1\n")

with open(os.path.join(args.gen, "bo2zm_locals.cpp"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/localize.py from the functions in app/locals.txt. Do not edit, do not commit.\n"
            "// Guest memory without volatile: plain loads and stores the compiler may keep in registers.\n"
            "#include <cstring>\n"
            "#include \"bo2zm_locals.h\"\n\n"
            "namespace {\n"
            "template <typename T> inline T LocalLoad(const uint8_t* p) { T v; std::memcpy(&v, p, sizeof(T)); return v; }\n"
            "template <typename T> inline void LocalStore(uint8_t* p, T v) { std::memcpy(p, &v, sizeof(T)); }\n"
            "}  // namespace\n"
            + "".join(f"REX_EXTERN({c});\n" for c in sorted(callees)) +
            "#undef REX_LOAD_U8\n#undef REX_LOAD_U16\n#undef REX_LOAD_U32\n#undef REX_LOAD_U64\n"
            "#undef REX_STORE_U8\n#undef REX_STORE_U16\n#undef REX_STORE_U32\n#undef REX_STORE_U64\n"
            "#define REX_LOAD_U8(x) LocalLoad<u8>(REX_RAW_ADDR(x))\n"
            "#define REX_LOAD_U16(x) __builtin_bswap16(LocalLoad<u16>(REX_RAW_ADDR(x)))\n"
            "#define REX_LOAD_U32(x) __builtin_bswap32(LocalLoad<u32>(REX_RAW_ADDR(x)))\n"
            "#define REX_LOAD_U64(x) __builtin_bswap64(LocalLoad<u64>(REX_RAW_ADDR(x)))\n"
            "#define REX_STORE_U8(x, y) LocalStore<u8>(REX_RAW_ADDR(x), u8(y))\n"
            "#define REX_STORE_U16(x, y) LocalStore<u16>(REX_RAW_ADDR(x), __builtin_bswap16(u16(y)))\n"
            "#define REX_STORE_U32(x, y) LocalStore<u32>(REX_RAW_ADDR(x), __builtin_bswap32(u32(y)))\n"
            "#define REX_STORE_U64(x, y) LocalStore<u64>(REX_RAW_ADDR(x), __builtin_bswap64(u64(y)))\n\n"
            + "\n".join(cpp_parts))
with open(os.path.join(args.gen, "bo2zm_locals.h"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/localize.py. Do not edit, do not commit.\n#pragma once\n"
            "#include <cstdint>\n#include <rex/ppc.h>\n\n" + "".join(header_lines))
print(f"localize: {len(fn_names)} functions written to bo2zm_locals.cpp")
