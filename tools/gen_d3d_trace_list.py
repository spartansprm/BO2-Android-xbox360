import json, os, struct
ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
fns = json.load(open(os.path.join(ROOT, "work", "gen_index.json")))
LO, HI, RESERVE = 0x82160000, 0x82190000, "82161700"
IMAGE, IMAGE_BASE = os.path.join(ROOT, "work", "dump_tu18", "default_mp.image.bin"), 0x82000000
SETTER_TABLES = [(0x82A9F618, 101), (0x82A9FAD8, 20)]
NO_OP_SETTER = "82685BF8"
HOOKED_ELSEWHERE = {"82174F38", "82175178", "821752D0", "82175420", "82169BF8", "821698D8"}
inside = lambda n: LO <= int(n, 16) < HI
reserve_callers = set(fns[RESERVE]["callers"])
image = open(IMAGE, "rb").read()
setters = set()
for table, entries in SETTER_TABLES:
    for i in range(entries):
        at = table + 12 * i + 4 - IMAGE_BASE
        setter = "%08X" % struct.unpack(">I", image[at:at + 4])[0]
        if setter != NO_OP_SETTER and inside(setter) and setter in fns:
            setters.add(setter)
picked = []
for n in sorted(fns):
    if not inside(n) or n in HOOKED_ELSEWHERE:
        continue
    ext = [c for c in fns[n]["callers"] if not inside(c)]
    if ext or n in reserve_callers or n in setters:
        picked.append(n)
out = os.path.join(ROOT, "app", "src", "bo2zm_d3d_trace_list.inc")
with open(out, "w", newline="\n") as f:
    f.write("// Generated by tools/gen_d3d_trace_list.py; do not edit. X(address)\n")
    for n in picked:
        f.write(f"X({n})\n")
print(len(picked), "functions ->", out, f"({len(setters)} state setters)")
